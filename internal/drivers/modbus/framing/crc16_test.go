package framing_test

import (
	"testing"

	"github.com/dxinli/collect-code/internal/drivers/modbus/framing"
)

func TestCRC16KnownVectors(t *testing.T) {
	tests := []struct {
		name string
		raw  []byte
		want uint16
	}{
		{"check value", []byte("123456789"), 0x4B37},
		{"read holding two", []byte{0x01, 0x03, 0x00, 0x00, 0x00, 0x02}, 0x0BC4},
		{"read holding ten", []byte{0x01, 0x03, 0x00, 0x00, 0x00, 0x0A}, 0xCDC5},
		{"read input one", []byte{0x01, 0x04, 0x00, 0x00, 0x00, 0x01}, 0xCA31},
		{"write single", []byte{0x01, 0x06, 0x00, 0x02, 0x00, 0x32}, 0xDFA9},
		{"write multiple request", []byte{0x01, 0x10, 0x00, 0x02, 0x00, 0x02, 0x04, 0x00, 0x32, 0x00, 0x64}, 0x52D2},
		{"read holding response", []byte{0x01, 0x03, 0x04, 0x00, 0x32, 0x00, 0x64}, 0x175A},
		{"read input response", []byte{0x01, 0x04, 0x02, 0xFF, 0xFF}, 0x80B8},
		{"write multiple response", []byte{0x01, 0x10, 0x00, 0x02, 0x00, 0x02}, 0x08E0},
		{"exception", []byte{0x01, 0x83, 0x02}, 0xF1C0},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := framing.CRC16(tt.raw); got != tt.want {
				t.Fatalf("CRC16 = 0x%04X, want 0x%04X", got, tt.want)
			}
		})
	}
}

func TestCRC16WireByteOrder(t *testing.T) {
	crc := framing.CRC16([]byte{0x01, 0x03, 0x00, 0x00, 0x00, 0x02})
	if byte(crc) != 0xC4 || byte(crc>>8) != 0x0B {
		t.Fatalf("wire bytes = %02X %02X, want C4 0B", byte(crc), byte(crc>>8))
	}
}
